// The window's only door to the main process: a few named calls and one
// stream of events.
const { contextBridge, ipcRenderer, webUtils } = require("electron");

contextBridge.exposeInMainWorld("vivo", {
  estado: () => ipcRenderer.invoke("estado"),
  enviar: (texto, anexos) => ipcRenderer.invoke("enviar", texto, anexos),
  parar: () => ipcRenderer.invoke("parar"),
  pararTarefa: (id) => ipcRenderer.invoke("parar_tarefa", id),
  permissao: (id, decisao, extra) => ipcRenderer.invoke("permissao", { id, decisao, ...extra }),
  nova: () => ipcRenderer.invoke("nova"),
  novaEm: (cwd) => ipcRenderer.invoke("nova_em", cwd),
  injetar: (texto, anexos) => ipcRenderer.invoke("injetar", texto, anexos),
  sessoes: (opcoes) => ipcRenderer.invoke("sessoes", opcoes),
  abrirSessao: (id, cwd) => ipcRenderer.invoke("abrir_sessao", id, cwd),
  pasta: () => ipcRenderer.invoke("pasta"),
  renomear: (id, titulo, cwd) => ipcRenderer.invoke("renomear", { id, titulo, cwd }),
  apagar: (id, cwd) => ipcRenderer.invoke("apagar", id, cwd),
  config: (mudanca) => ipcRenderer.invoke("config", mudanca),
  barra: (claro) => ipcRenderer.invoke("barra", claro),
  link: (url) => ipcRenderer.invoke("link", url),
  abrirLink: (href) => ipcRenderer.invoke("abrir_link", href),
  comandos: () => ipcRenderer.invoke("comandos"),
  arquivos: (atualiza) => ipcRenderer.invoke("arquivos", atualiza),
  saida: (id) => ipcRenderer.invoke("saida", id),
  anexar: () => ipcRenderer.invoke("anexar"),
  // A dropped file's path on disk ("" for pasted data, which has none).
  // main only trusts for "abrir_arquivo" the paths read here from real File objects
  caminhoDe: (arquivo) => { try { const p = webUtils.getPathForFile(arquivo) || ""; if (p) ipcRenderer.send("anexo_soltou", p); return p; } catch { return ""; } },
  motionImportar: (caminho) => ipcRenderer.invoke("motion_importar", caminho),
  motionLista: () => ipcRenderer.invoke("motion_lista"),
  motionLer: (id) => ipcRenderer.invoke("motion_ler", id),
  motionApagar: (id) => ipcRenderer.invoke("motion_apagar", id),
  ramificar: (id, uuid, titulo, cwd) => ipcRenderer.invoke("ramificar", { id, uuid, titulo, cwd }),
  exportar: (id, titulo, cwd) => ipcRenderer.invoke("exportar", { id, titulo, cwd }),
  buscar: (termo, todas) => ipcRenderer.invoke("buscar", termo, todas),
  focar: () => ipcRenderer.invoke("focar"),
  visual: () => ipcRenderer.invoke("visual"),
  i18n: () => ipcRenderer.sendSync("i18n"),
  visualSalvar: (v) => ipcRenderer.invoke("visual_salvar", v),
  pessoalLista: (tipo) => ipcRenderer.invoke("pessoal_lista", tipo),
  pessoalImportar: (tipo, caminhos) => ipcRenderer.invoke("pessoal_importar", tipo, caminhos),
  pessoalApagar: (tipo, id) => ipcRenderer.invoke("pessoal_apagar", tipo, id),
  weLista: () => ipcRenderer.invoke("we_lista"),
  conta: () => ipcRenderer.invoke("conta"),
  contaSalvar: (dados) => ipcRenderer.invoke("conta_salvar", dados),
  claudeChecar: () => ipcRenderer.invoke("claude_checa"),
  claudeInstalar: () => ipcRenderer.invoke("claude_instalar"),
  claudeEntrar: (opcoes) => ipcRenderer.invoke("claude_entrar", opcoes),
  claudeCodigo: (codigo) => ipcRenderer.invoke("claude_codigo", codigo),
  claudeEntrarCancela: () => ipcRenderer.invoke("claude_entrar_cancela"),
  weImportar: (pasta) => ipcRenderer.invoke("we_importar", pasta),
  responder: (id, respostas) => ipcRenderer.invoke("responder", { id, respostas }),
  desfazer: (uuid, simular) => ipcRenderer.invoke("desfazer", { uuid, simular }),
  janelaNova: (sessao) => ipcRenderer.invoke("janela_nova", sessao),
  painel: () => ipcRenderer.invoke("painel"),
  mcpAcao: (acao, nome, escopo) => ipcRenderer.invoke("mcp_acao", { acao, nome, escopo }),
  mcpAdicionar: (dados) => ipcRenderer.invoke("mcp_adicionar", dados),
  uso: (fundo) => ipcRenderer.invoke("uso", fundo),
  novidades: () => ipcRenderer.invoke("novidades"),
  abrirArquivo: (caminho, naPasta) => ipcRenderer.invoke("abrir_arquivo", caminho, naPasta),
  gitAlteracoes: () => ipcRenderer.invoke("git_alteracoes"),
  gitReverter: (caminho) => ipcRenderer.invoke("git_reverter", caminho),
  ramo: () => ipcRenderer.invoke("ramo"),
  worktreeInfo: (cwd) => ipcRenderer.invoke("worktree_info", cwd),
  worktreeCriar: (texto) => ipcRenderer.invoke("worktree_criar", texto),
  worktreeRemover: (cwd) => ipcRenderer.invoke("worktree_remover", cwd),
  prInfo: () => ipcRenderer.invoke("pr_info"),
  prCriar: () => ipcRenderer.invoke("pr_criar"),
  termEnviar: (linha) => ipcRenderer.invoke("term_enviar", linha),
  termParar: () => ipcRenderer.invoke("term_parar"),
  atualizacao: () => ipcRenderer.invoke("atualizacao"),
  atualizacaoProcurar: () => ipcRenderer.invoke("atualizacao_procurar"),
  atualizacaoInstalar: () => ipcRenderer.invoke("atualizacao_instalar"),
  remoto: () => ipcRenderer.invoke("remoto"),
  remotoLigar: (ligar) => ipcRenderer.invoke("remoto_ligar", ligar),
  aoEvento: (fn) => ipcRenderer.on("evento", (_e, ev) => fn(ev)),
});
